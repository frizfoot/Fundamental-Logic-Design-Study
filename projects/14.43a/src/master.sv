`timescale 1ns / 1ps                      // 시간 단위 1ns, 정밀도 1ps. #1 이라고 쓰면 1ns 를 뜻한다
//////////////////////////////////////////////////////////////////////////////////
// Module Name: master
// 문제 14.43(a) - Manchester → NRZ 변환기 (Mealy, 상태 3개)
//
//   입력  x : Manchester.  데이터 0 = "0 1" ,  데이터 1 = "1 0"
//   출력  z : NRZ.         한 비트 시간(= clk 두 주기) 동안 같은 값 유지
//   clk     : 데이터 비트율의 2배 주파수 (교재의 Clock2)
//////////////////////////////////////////////////////////////////////////////////


module master #(                          // 모듈 선언. #( 로 파라미터 목록이 시작된다
    parameter dc1=1'b0,                   // S1 행의 don't care 칸에 채울 출력값 (기본 0 = 정답)
    parameter dc2=1'b1                    // S2 행의 don't care 칸에 채울 출력값 (기본 1 = 정답)
    )(                                    // 여기서부터 포트(실제 전선) 목록
    input  logic x, clk, rst_n,           // 입력 3개. rst_n 의 _n 은 "0일 때 리셋"이라는 관례 표기
    output logic z                        // 출력 1개
    );
    localparam[1:0]                       // localparam = 밖에서 못 바꾸는 상수. [1:0] 은 2비트짜리
        s0=2'b00,                         // 첫 글자 받을 차례 (비트 경계)
        s1=2'b01,                         // 둘째 글자 차례, 첫 글자가 0이었음 → 데이터 0
        s2=2'b10;                         // 둘째 글자 차례, 첫 글자가 1이었음 → 데이터 1
     reg[1:0] state;                      // 상태를 담는 2비트 레지스터 = 플립플롭 2개

    //-----------------------------------------------------------------
    // 블록 ① 다음 상태 - 상태표의 "NS" 열
    //-----------------------------------------------------------------
    always_ff@(posedge clk or negedge rst_n) begin   // "이건 플립플롭이다" 선언.
                                                     // clk 올라갈 때 또는 rst_n 떨어질 때만 동작
        if (!rst_n)                       // rst_n 이 0 이면 (! 는 NOT)
            state<=s0;                    // 비동기 리셋 - 클럭 안 기다리고 즉시 S0
        else begin                        // 평상시
            case(state)                   // 현재 상태에 따라 분기 = 상태표의 행 고르기
                s0: state<=x? s2:s1;      // S0 행: x=1 → S2,  x=0 → S1   (첫 글자가 곧 데이터)
                s1: state<=x? s0:s1;      // S1 행: x=1 → S0 (정상).  x=0 은 안 옴 → 제자리
                s2: state<=x? s2:s0;      // S2 행: x=0 → S0 (정상).  x=1 은 안 옴 → 제자리
                default: state<=s0;       // 쓰지 않는 상태 2'b11 에 빠지면 S0 으로 복구 (safe FSM)
            endcase
        end
    end                                   // <= 는 nonblocking 대입. 순차회로에선 항상 이걸 쓴다

    //-----------------------------------------------------------------
    // 블록 ② 출력 - 상태표의 "Z" 열
    //   assign = 조합회로(전선+게이트). 클럭을 안 거치므로 x 가 z 에 직통한다 → Mealy
    //-----------------------------------------------------------------
    assign z = (state==s0)?x              // S0 이면        : z = x        (x=0→0, x=1→1 이라 그냥 x)
             :(state==s1) ?(x?1'b0:dc1)   // 아니고 S1 이면 : x=1 → 0 (정상),  x=0 → dc1 (don't care)
             : (x?dc2:1'b1);              // 그것도 아니면  : x=1 → dc2 (don't care),  x=0 → 1 (정상)
                                          //   ? 는 "~이면", : 는 "아니면". 1'b1 은 1비트짜리 1
                                          //   dc1=0, dc2=1 로 두면 S1/S2 행이 상수가 되어
                                          //   그 상태에서는 x 가 z 에 영향을 못 준다 → 글리치 제거
endmodule